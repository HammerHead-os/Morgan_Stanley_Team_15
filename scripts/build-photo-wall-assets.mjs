import { execFile } from "node:child_process";
import { createHash } from "node:crypto";
import {
  mkdir,
  readFile,
  readdir,
  stat,
  writeFile,
} from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { promisify } from "node:util";

const execFileAsync = promisify(execFile);
const scriptDir = path.dirname(fileURLToPath(import.meta.url));
const repoRoot = path.resolve(scriptDir, "..");
const defaultSource = path.resolve(
  repoRoot,
  "../Documents/Code To Give/public/imported",
);
const sourceRoot = path.resolve(process.argv[2] || defaultSource);
const outputDir = path.join(repoRoot, "docs/assets/photo-wall");
const manifestPath = path.join(repoRoot, "docs/js/photo-wall-manifest.js");
const supportedExtensions = new Set([".gif", ".jpeg", ".jpg", ".png", ".webp"]);

async function collectImages(directory) {
  const entries = await readdir(directory, { withFileTypes: true });
  const files = [];

  for (const entry of entries) {
    const fullPath = path.join(directory, entry.name);
    if (entry.isDirectory()) {
      files.push(...(await collectImages(fullPath)));
    } else if (supportedExtensions.has(path.extname(entry.name).toLowerCase())) {
      files.push(fullPath);
    }
  }

  return files;
}

async function sha1(filePath) {
  const data = await readFile(filePath);
  return createHash("sha1").update(data).digest("hex");
}

async function buildRecord(filePath, index, seenHashes) {
  const hash = await sha1(filePath);
  if (seenHashes.has(hash)) return null;
  seenHashes.add(hash);

  const filename = `${String(index + 1).padStart(4, "0")}-${hash.slice(0, 10)}.jpg`;
  return {
    source: filePath,
    output: path.join(outputDir, filename),
    publicPath: `assets/photo-wall/${filename}`,
  };
}

async function convert(record) {
  try {
    const existing = await stat(record.output);
    if (existing.size > 0) return { ...record, skipped: true };
  } catch {
    // The thumbnail does not exist yet.
  }

  await execFileAsync("/usr/bin/sips", [
    "-Z",
    "320",
    "-s",
    "format",
    "jpeg",
    "-s",
    "formatOptions",
    "45",
    record.source,
    "--out",
    record.output,
  ]);
  return record;
}

async function mapWithConcurrency(items, limit, worker) {
  const results = new Array(items.length);
  let nextIndex = 0;

  async function run() {
    while (nextIndex < items.length) {
      const index = nextIndex;
      nextIndex += 1;
      try {
        results[index] = await worker(items[index]);
      } catch (error) {
        results[index] = {
          ...items[index],
          error: error instanceof Error ? error.message : String(error),
        };
      }
    }
  }

  await Promise.all(Array.from({ length: limit }, run));
  return results;
}

await mkdir(outputDir, { recursive: true });

const sourceFiles = (await collectImages(sourceRoot)).sort((a, b) =>
  a.localeCompare(b),
);
const seenHashes = new Set();
const records = [];

for (const filePath of sourceFiles) {
  const record = await buildRecord(filePath, records.length, seenHashes);
  if (record) records.push(record);
}

const results = await mapWithConcurrency(records, 8, convert);
const successful = results.filter((item) => !item.error);
const failed = results.filter((item) => item.error);
const manifest = successful.map((item) => item.publicPath);
const sourceLabel = path.relative(repoRoot, sourceRoot);

await writeFile(
  manifestPath,
  [
    "/* Generated by scripts/build-photo-wall-assets.mjs. */",
    `window.LOVE21_PHOTO_WALL_SOURCE = ${JSON.stringify(sourceLabel)};`,
    `window.LOVE21_PHOTO_WALL = Object.freeze(${JSON.stringify(manifest, null, 2)});`,
    "",
  ].join("\n"),
);

console.log(
  JSON.stringify(
    {
      sourceFiles: sourceFiles.length,
      uniqueImages: records.length,
      generated: successful.filter((item) => !item.skipped).length,
      reused: successful.filter((item) => item.skipped).length,
      skippedInvalidFiles: failed.length,
      outputDir,
      manifestPath,
    },
    null,
    2,
  ),
);

if (failed.length) {
  console.warn(
    failed
      .slice(0, 20)
      .map((item) => `Skipped non-decodable file: ${item.source}`)
      .join("\n"),
  );
}
